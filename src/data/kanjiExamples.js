const toHiragana = (value = '') => value.replace(/[\u30a1-\u30f6]/g, (character) => String.fromCharCode(character.charCodeAt(0) - 0x60));
const normalizeReadings = (value = '') => toHiragana(value)
  .split(/[、,・/\s]+/)
  .map((reading) => reading.replace(/[()（）.-]/g, '').trim())
  .filter((reading) => reading && reading !== 'なし');

const readingKind = (item, word) => {
  const reading = toHiragana(word.reading || word.wordReading || '');
  const on = normalizeReadings(item.onyomi);
  const kun = normalizeReadings(item.kunyomi);
  if (on.some((value) => value.length > 1 && reading.includes(value))) return 'on';
  if (kun.some((value) => value.length > 1 && reading.includes(value.replace(/[るうくぐすつぬぶむ]$/, '')))) return 'kun';
  return word.word === item.word && /[ぁ-ん]/.test(item.kunyomi) ? 'kun' : 'on';
};

