const framesFor = (word) => {
  const type = word.type || '';
  if (/Verb/.test(type)) return verbFrames;
  if (/Adjective/.test(type)) return adjectiveFrames;
  if (/Expression|Interjection|Adverb/.test(type)) return expressionFrames;
  return nounFrames;
};

const makeExamples = (item, words) => {
  const representative = {
    word: item.word,
    reading: item.wordReading,
    meaning: item.wordMeaning,
    type: /[るうくぐすつぬぶむ]$/.test(item.word) ? 'Verb' : /い$/.test(item.word) ? 'Adjective' : 'Noun',
  };
  const pool = [representative, ...words].filter((word, index, all) => all.findIndex((entry) => entry.word === word.word) === index);
  const grouped = {
    on: pool.filter((word) => readingKind(item, word) === 'on'),
    kun: pool.filter((word) => readingKind(item, word) === 'kun'),
  };
  const availableKinds = [
    ...(normalizeReadings(item.onyomi).length ? ['on'] : []),
    ...(normalizeReadings(item.kunyomi).length ? ['kun'] : []),
  ];
  const kinds = availableKinds.length ? availableKinds : ['on'];
  const examples = [];
  for (let index = 0; index < 10; index += 1) {
    const kind = kinds[index % kinds.length];
    const candidates = grouped[kind].length ? grouped[kind] : pool;
    const word = candidates[index % candidates.length];
    const frames = framesFor(word);
    const [japanese, english] = frames[index % frames.length](
      word.word,
      (word.meaning || item.meaning).split(';')[0].replace(/^to /, ''),
    );
    examples.push({
      readingType: grouped[kind].length ? kind : readingKind(item, word),
      word: word.word,
      reading: word.reading || word.wordReading,
      japanese,
      english,
    });
  }
  return examples;
};

export const buildKanjiExamples = (item, words) => (curated[item.character] || makeExamples(item, words))
  .map((example) => Array.isArray(example)
    ? { readingType: example[0], word: example[1], reading: example[2], japanese: example[3], english: example[4] }
    : example);

